@pytest.fixture
def watched(kept, monkeypatch, tmp_path):
    plugin = kept.plugin
    calls = SimpleNamespace(posted=[], info=_fixture("info_printing_s1.json"), events=[])
    monkeypatch.setattr(plugin, "ANYCUBIC_CONFIG_FILE", str(tmp_path / ".fh_anycubic.json"))
    monkeypatch.setattr(plugin, "_ANYCUBIC_KNOWN_HOSTS", {})
    monkeypatch.setattr(plugin, "plugin_source_instance_id", lambda: "desktop-source-instance")
    monkeypatch.setattr(plugin, "USAGE_WATCH_SNAPSHOT_MIN_SECONDS", 0.0)
    monkeypatch.setitem(plugin._ANYCUBIC_CONNECTIONS, "items", [_connection()])

    def status(connection, serial=""):
        return {
            "serial": SERIAL, "model_id": "20025", "model_name": "Anycubic Kobra S1",
            "info": calls.info["data"],
            # The ACE feeds from its slot 2.
            "boxes": _fixture("multicolorbox_ace_pro.json")["data"], "holder": None,
        }, None

    def pair(path, token, payload):
        return 200, json.dumps({
            "bridge_token": "fhpb_" + "c" * 40, "physical_printer_id": 7,
            "material_system_id": 9, "printer_discovery_key": DISCOVERY_KEY,
        }).encode("utf-8")

    def post(path, token, payload):
        calls.posted.append((path, payload))
        if path == "/printer-bridge/usage-batches":
            calls.events.extend(payload["events"])
            answer = {"accepted": True, "ack_sequence": payload["sequence"]}
            return 200, json.dumps(answer).encode("utf-8"), None
        return 200, b"{}", None

    desired = {"slots": [{"index": 2, "spool": {"id": 11}}]}
    monkeypatch.setattr(plugin, "read_anycubic_status", status)
    monkeypatch.setattr(plugin, "http_post_json", pair)
    monkeypatch.setattr(plugin, "http_post_bridge_json", post)
    monkeypatch.setattr(
        plugin, "http_get_bridge_json", lambda *_args: (200, json.dumps(desired).encode("utf-8"))
    )
    monkeypatch.setattr(plugin, "revoke_fresh_bridge_token", lambda _token: None)
    assert plugin.configure_anycubic_bridge(7, 9, "FH-AAAAA-BBBBB", "", [_connection()])["ok"]
    calls.posted.clear()
    runtime = plugin.AnycubicWatchRuntime()

    def at_layer(layer, state="printing"):
        info = copy.deepcopy(calls.info)
        info["data"]["project"].update(curr_layer=layer, state=state)
        calls.info = info
        return runtime.watch_once()

    return SimpleNamespace(plugin=plugin, calls=calls, runtime=runtime, at_layer=at_layer)


def _charged(events):
    return [item for event in events for item in event["items"]]


def test_an_anycubic_job_is_charged_the_slicer_estimate_of_its_layers(watched, kept):
    _keep_slice(kept.plugin, kept.tmp, "bracket_PLA_0.2.gcode")
    plugin = watched.plugin

    # Linked mid-job: what was printed before the first reading is not charged.
    assert watched.at_layer(48) == plugin.USAGE_WATCH_PRINTING_SECONDS
    snapshot = next(payload for path, payload in watched.calls.posted if path.endswith("snapshot"))
    assert "consumption" in snapshot["capabilities"]
    watched.at_layer(58)
    # Layers 61 and 62 change tools: the stretch around them is charged to nobody.
    watched.at_layer(64)
    assert watched.at_layer(LAYERS, state="finished") == plugin.USAGE_WATCH_IDLE_SECONDS
    watched.at_layer(LAYERS, state="finished")

    items = _charged(watched.calls.events)
    assert [round(item["used_length_mm"], 1) for item in items] == [10.0, 66.0]
    assert {(item["slot_index"], item["spool_id"]) for item in items} == {(2, 11)}
    assert {(item["consumption_kind"], item["estimate_source"]) for item in items} == {
        ("estimated", "slicer_gcode"),
    }
    terminal = watched.calls.events[-1]
    assert terminal["event_type"] == "terminal" and terminal["outcome"] == "completed"
    assert terminal["file_name"] == "bracket_PLA_0.2.gcode.3mf"


def test_the_figures_stay_for_the_job_when_its_g_code_copy_is_gone(watched, kept):
    path = _keep_slice(kept.plugin, kept.tmp, "bracket_PLA_0.2.gcode", _gcode(second=()))

    watched.at_layer(48)
    # Newer slices pushed the copy out of the cache in the middle of the print.
    path.unlink()
    watched.at_layer(58)
    watched.at_layer(LAYERS, state="finished")
    watched.at_layer(LAYERS, state="finished")

    assert round(sum(item["used_length_mm"] for item in _charged(watched.calls.events)), 1) == 82.0


def test_a_job_sliced_elsewhere_ends_as_not_counted_with_the_reason(watched):
    watched.at_layer(48)
    watched.at_layer(80)
    watched.at_layer(LAYERS, state="finished")
    watched.at_layer(LAYERS, state="finished")

    assert _charged(watched.calls.events) == []
    terminal = watched.calls.events[-1]
    assert terminal["outcome"] == "completed"
    assert terminal["skipped"] == [{"reason": "print_not_sliced_here"}]
