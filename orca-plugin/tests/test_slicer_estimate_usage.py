"""Printers that count no filament are charged the slicer's estimate of the job.

Anycubic, Elegoo (SDCP and MQTT) and Prusa report the job, its layer or its
progress, never the filament it used. The plugin finds its own copy of the
job's G-code by name and charges OrcaSlicer's figure through the layer the
printer is on.
"""

from __future__ import annotations

import copy
import json
import os
from types import SimpleNamespace

import pytest

from .test_anycubic import DISCOVERY_KEY, SERIAL, _connection, _fixture

LAYERS = 130
# The second tool prints layers 61 and 62 only: a change in, and one back out.
SECOND_TOOL_LAYERS = (61, 62)


def _gcode(layers=LAYERS, second=SECOND_TOOL_LAYERS, per_layer_mm=1.0):
    lines = ["; generated by OrcaSlicer 2.3.1", "M83", "T0"]
    tool = 0
    used = [0.0, 0.0]
    for layer in range(1, layers + 1):
        lines.append(";LAYER_CHANGE")
        wanted = 1 if layer in second else 0
        if wanted != tool:
            lines.append("T%d" % wanted)
            tool = wanted
        lines.append("G1 X10 Y10 E%.3f" % per_layer_mm)
        used[tool] += per_layer_mm
    lines.append("; filament used [mm] = %.2f, %.2f" % tuple(used))
    lines.append("; filament used [g] = %.2f, %.2f" % tuple(value * 0.003 for value in used))
    return "\n".join(lines) + "\n"


def _keep_slice(plugin, tmp_path, name, text=None, key="k1"):
    cache = tmp_path / "slices"
    cache.mkdir(exist_ok=True)
    path = cache / (key + ".gcode")
    path.write_bytes((text if text is not None else _gcode()).encode("utf-8"))
    index_path = tmp_path / "slices.json"
    index = json.loads(index_path.read_text(encoding="utf-8")) if index_path.exists() else {}
    index[key] = {"path": str(path), "name": name}
    index_path.write_text(json.dumps(index), encoding="utf-8")
    return path


@pytest.fixture
def kept(plugin_module, monkeypatch, tmp_path):
    monkeypatch.setattr(plugin_module, "_SLICE_INDEX_FILE", str(tmp_path / "slices.json"))
    monkeypatch.setattr(plugin_module, "_SLICE_CACHE_DIR", str(tmp_path / "slices"))
    monkeypatch.setattr(plugin_module, "_SLICE_PROFILES", {})
    return SimpleNamespace(plugin=plugin_module, tmp=tmp_path)


def test_the_g_code_gives_length_and_tool_changes_layer_by_layer(kept):
    path = _keep_slice(kept.plugin, kept.tmp, "bracket.gcode")

    profile = kept.plugin._slice_length_profile(str(path))

    assert len(profile["lengths"]) == LAYERS and profile["total_mm"] == 130.0
    assert profile["lengths"][47] == 48.0
    # Into the second tool at layer 61, back at layer 63.
    assert profile["switches"][59] == 0
    assert profile["switches"][60] == 1 and profile["switches"][61] == 1
    assert profile["switches"][62] == 2 and profile["switches"][-1] == 2


def test_a_job_is_found_by_the_name_the_printer_gives_it(kept):
    _keep_slice(kept.plugin, kept.tmp, "bracket PLA 0.2.gcode")

    # The printer keeps the upload as .gcode.3mf and spells spaces as underscores.
    found = kept.plugin.slicer_job_estimate("bracket_PLA_0.2.gcode.3mf", LAYERS)

    assert found["total_mm"] == 130.0 and found["job"] == "bracket_PLA_0.2.gcode.3mf"
    # A slice of another layer count is another job.
    assert kept.plugin.slicer_job_estimate("bracket_PLA_0.2.gcode.3mf", 90) is None
    assert kept.plugin.slicer_job_estimate("other.gcode", LAYERS) is None


def test_two_slices_of_one_name_that_disagree_are_not_guessed_between(kept):
    _keep_slice(kept.plugin, kept.tmp, "bracket.gcode", key="old")
    _keep_slice(kept.plugin, kept.tmp, "bracket.gcode", _gcode(per_layer_mm=1.5), key="new")

    # Without a layer count to tell them apart (PrusaLink reports none).
    assert kept.plugin.slicer_job_estimate("bracket.gcode") is None


def test_binary_g_code_has_no_figures(kept):
    path = kept.tmp / "slices"
    path.mkdir()
    binary = path / "k1.gcode"
    binary.write_bytes(b"GCDE\x01\x00\x00\x00" + b"\x00" * 64)
    index = {"k1": {"path": str(binary), "name": "bracket.bgcode"}}
    (kept.tmp / "slices.json").write_text(json.dumps(index), encoding="utf-8")

    assert kept.plugin.slicer_job_estimate("bracket.bgcode") is None


