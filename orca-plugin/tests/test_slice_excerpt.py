def test_a_retired_plugin_generation_stops_a_long_read_without_an_answer(
    plugin_module, monkeypatch, tmp_path
):
    source = tmp_path / "slice.gcode"
    _big_gcode(source, 8 * MIB)
    catalog, delivered = _catalog(
        plugin_module, monkeypatch, tmp_path, {"path": str(source), "name": "slice.gcode"}
    )
    monkeypatch.setattr(plugin_module, "_SLICE_READ_CHUNK", 256 * 1024)
    worker = plugin_module.ReusableDaemonWorker("filamenthub-slice-test")
    monkeypatch.setattr(plugin_module, "BACKGROUND_WORKER", worker)
    posted = []
    monkeypatch.setattr(
        plugin_module, "http_post_slice_excerpt", lambda *args: posted.append(args)
    )
    seen_chunks = []
    real_sleep = plugin_module.time.sleep

    def retire_after_first_chunk(seconds):
        seen_chunks.append(seconds)
        if len(seen_chunks) == 2:
            worker.stop(wait_timeout=0)
        real_sleep(0)

    monkeypatch.setattr(plugin_module.time, "sleep", retire_after_first_chunk)
    done = threading.Event()

    def job():
        worker_generation = worker.current_job_generation()
        worker.run_in_generation(
            worker_generation, catalog._parse_slice, "k6", "token", str(source), "slice.gcode"
        )
        done.set()

    assert worker.submit(job)
    assert done.wait(10)

    assert posted == []
    assert _results(delivered) == []
    assert len(seen_chunks) < 8 * MIB // (256 * 1024)
    worker.stop(wait_timeout=0)


def test_only_one_slice_is_read_at_a_time_and_a_free_slot_runs_in_its_own_thread(
    plugin_module, monkeypatch, tmp_path
):
    source = tmp_path / "slice.gcode"
    source.write_bytes(b"; x\n")
    catalog, delivered = _catalog(
        plugin_module, monkeypatch, tmp_path, {"path": str(source), "name": "slice.gcode"}
    )
    started = threading.Event()
    release = threading.Event()
    ran_on = []

    def slow_parse(key, token, path, name):
        ran_on.append(threading.current_thread().name)
        started.set()
        assert release.wait(5)

    monkeypatch.setattr(catalog, "_parse_slice", slow_parse)

    catalog._do_parse_slice("first", "token", "slice.gcode")
    assert started.wait(5)
    catalog._do_parse_slice("second", "token", "slice.gcode")
    release.set()
    for _ in range(100):
        if plugin_module._SLICE_PARSE_LOCK.acquire(False):
            plugin_module._SLICE_PARSE_LOCK.release()
            break
        threading.Event().wait(0.05)

    assert ran_on == ["filamenthub-slice-parse"]
    assert _results(delivered) == [{"sourceKey": "second", "error": "busy"}]


def test_a_slice_whose_file_is_gone_or_without_a_session_is_answered_at_once(
    plugin_module, monkeypatch, tmp_path
):
    catalog, delivered = _catalog(plugin_module, monkeypatch, tmp_path, None)
    catalog._do_parse_slice("gone-key", "token")
    monkeypatch.setattr(
        plugin_module, "slice_entry_for_key", lambda key: {"path": "x", "name": "x.gcode"}
    )
    catalog._do_parse_slice("auth-key", "")

    assert _results(delivered) == [
        {"sourceKey": "gone-key", "error": "gone"},
        {"sourceKey": "auth-key", "error": "auth"},
    ]
