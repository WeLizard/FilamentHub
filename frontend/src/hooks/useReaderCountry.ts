import { useAuth } from '../contexts/AuthContext';

/**
 * Страна, под которую подставлять местные сведения.
 *
 * Источник истины — подтверждённый выбор человека в профиле. Определение по
 * адресу подключения годится только на то, чтобы заранее подставить значение в
 * форму, которое он подтвердит или изменит, поэтому здесь его нет.
 *
 * Не определилось — возвращаем `undefined`, и каталог показывает общее, молча.
 */
export function useReaderCountry(): string | undefined {
  const { user } = useAuth();
  return user?.country ?? undefined;
}
