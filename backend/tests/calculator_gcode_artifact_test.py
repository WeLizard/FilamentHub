async def _upload(
    client: AsyncClient,
    payload: bytes,
    *,
    artifact_id: str | None = None,
    file_name: str = "plates.gcode.3mf",
):
    operation_id = artifact_id or str(uuid4())
    response = await client.put(
        f"/api/v1/calculator/gcode-artifacts/{operation_id}",
        params={"file_name": file_name, "expected_size_bytes": len(payload)},
        content=payload,
        headers={"Content-Type": "application/octet-stream"},
    )
    return operation_id, response


@pytest.mark.asyncio
async def test_one_upload_is_reused_for_every_plate_and_retry(
    auth_client: AsyncClient,
    artifact_storage,
) -> None:
    payload = _multi_plate_3mf()
    artifact_id, uploaded = await _upload(auth_client, payload)

    assert uploaded.status_code == 200
    assert uploaded.json()["state"] == "ready"
    assert len(list(artifact_storage.glob("*.bin"))) == 1

    parsed = await auth_client.post(
        f"/api/v1/calculator/gcode-artifacts/{artifact_id}/parse"
    )
    assert parsed.status_code == 200
    assert [job["plate_index"] for job in parsed.json()["jobs"]] == [1, 2]
    assert [job["total_filament_weight_g"] for job in parsed.json()["jobs"]] == [12.5, 4.5]

    # A lost upload response is recovered by the same operation ID. The original
    # immutable blob remains the only stored payload.
    _, retried = await _upload(auth_client, payload, artifact_id=artifact_id)
    assert retried.status_code == 200
    assert retried.json()["sha256"] == uploaded.json()["sha256"]
    assert len(list(artifact_storage.glob("*.bin"))) == 1


@pytest.mark.asyncio
async def test_artifact_is_owner_bound_and_delete_is_idempotent(
    auth_client: AsyncClient,
    client: AsyncClient,
    db_session: AsyncSession,
    artifact_storage,
) -> None:
    payload = _multi_plate_3mf()
    artifact_id, uploaded = await _upload(auth_client, payload)
    assert uploaded.status_code == 200

    other = User(
        email="artifact-other@example.com",
        username="artifactother",
        password_hash="$2b$12$test",
        active=True,
        email_verified=True,
        terms_version_accepted=CURRENT_TERMS_VERSION,
        personal_data_consent_version=CURRENT_PERSONAL_DATA_CONSENT_VERSION,
    )
    db_session.add(other)
    await db_session.commit()
    from app.core.security import create_access_token

    other_client_headers = {"Authorization": f"Bearer {create_access_token({'sub': other.email})}"}
    hidden = await client.get(
        f"/api/v1/calculator/gcode-artifacts/{artifact_id}",
        headers=other_client_headers,
    )
    assert hidden.status_code == 404

    deleted = await auth_client.delete(
        f"/api/v1/calculator/gcode-artifacts/{artifact_id}"
    )
    deleted_again = await auth_client.delete(
        f"/api/v1/calculator/gcode-artifacts/{artifact_id}"
    )
    assert deleted.status_code == deleted_again.status_code == 204
    cancelled = await auth_client.post(
        f"/api/v1/calculator/gcode-artifacts/{artifact_id}/parse"
    )
    assert cancelled.status_code == 409
    assert cancelled.json()["detail"]["code"] == "ERR_GCODE_ARTIFACT_CANCELLED"


