def _plain_gcode() -> bytes:
    return (
        "; generated by OrcaSlicer 2.4.0\n"
        "; estimated printing time (normal mode) = 1h 2m\n"
        "; total filament weight [g] : 12.5\n"
        "; filament_type = PLA\n"
        "; filament_settings_id = Generic PLA\n"
    ).encode()


def _multi_plate_3mf() -> bytes:
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("Metadata/plate_1.gcode", _plain_gcode())
        archive.writestr(
            "Metadata/plate_2.gcode",
            _plain_gcode().replace(b"12.5", b"4.5"),
        )
    return output.getvalue()


def _large_plain_gcode(size_bytes: int = 34 * 1024 * 1024) -> bytes:
    header = (
        "; generated by OrcaSlicer 2.4.0\n"
        "; estimated printing time (normal mode) = 6h 24m\n"
        "; total filament weight [g] : 120\n"
        "; filament_type = PETG\n"
        "M83\n"
    ).encode()
    move = b"G1 X1 Y1 E0.001\n"
    body_size = size_bytes - len(header)
    complete_moves, padding_size = divmod(body_size, len(move))
    padding = b"" if padding_size == 0 else b";" + b" " * (padding_size - 2) + b"\n"
    return header + move * complete_moves + padding


