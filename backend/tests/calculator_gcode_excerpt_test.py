def _orca_gcode(size_bytes: int = 6 * MIB) -> bytes:
    header = (
        "; HEADER_BLOCK_START\n"
        "; generated by OrcaSlicer 2.3.0 on 2026-09-01 at 10:00:00 UTC\n"
        "; HEADER_BLOCK_END\n"
        "EXCLUDE_OBJECT_DEFINE NAME=Cube_id_0 CENTER=100,100 POLYGON=[[1,1],[2,2]]\n"
        "M83\n"
    )
    footer = (
        "; filament used [mm] = 5000.00,0.00\n"
        "; filament used [cm3] = 12.00,0.00\n"
        "; filament used [g] = 14.88,0.00\n"
        "; filament cost = 0.30,0.00\n"
        "; total filament used [g] = 14.88\n"
        "; total layers count = 120\n"
        "; estimated first layer printing time (normal mode) = 1m 5s\n"
        "; estimated printing time (normal mode) = 8h 43m 10s\n"
        "; CONFIG_BLOCK_START\n"
        '; filament_settings_id = "Generic PETG";"Generic PLA"\n'
        "; filament_type = PETG;PLA\n"
        '; filament_vendor = "Generic";"Bambu Lab"\n'
        "; filament_colour = #FFFFFF;#000000\n"
        "; filament_density = 1.27,1.24\n"
        "; filament_diameter = 1.75,1.75\n"
        "; filament_id = GFG99;GFA00\n"
        "; fhub_identity_v1 = kind=material_preset;tool=0;id=34059\n"
        "; printer_model = Bambu Lab P1S\n"
        "; printer_settings_id = Bambu Lab P1S 0.4 nozzle\n"
        "; print_settings_id = 0.20mm Standard @BBL X1C\n"
        "; nozzle_diameter = 0.4\n"
        "; nozzle_temperature_initial_layer = 255,215\n"
        "; nozzle_temperature = 250,210\n"
        "; cool_plate_temp_initial_layer = 70,60\n"
        "; cool_plate_temp = 65,55\n"
        "; layer_height = 0.2\n"
        "; initial_layer_print_height = 0.2\n"
        "; sparse_infill_density = 15%\n"
        "; wall_loops = 3\n"
        "; CONFIG_BLOCK_END\n"
    )
    body_unit = (
        "EXCLUDE_OBJECT_START NAME=Cube_id_0\n"
        ";TYPE:Sparse infill\n"
        + "G1 X10.123 Y10.123 E0.0123\n" * 40
        + "EXCLUDE_OBJECT_END\n"
        + ";TYPE:Support\n"
        + "G1 X10.123 Y10.123 E0.0123\n" * 10
    )
    repeats = (size_bytes - len(header) - len(footer)) // len(body_unit) + 1
    return (header + body_unit * repeats + footer).encode()


def _assert_cut_mid_line(raw: bytes, head_end: int, tail_start: int) -> None:
    assert raw[head_end - 1 : head_end] != b"\n"
    assert raw[tail_start - 1 : tail_start] != b"\n"


def test_excerpt_summary_equals_the_full_parse_of_a_large_file() -> None:
    raw = _orca_gcode()
    assert len(raw) > 5 * MIB
    head_end, tail_start = MIB - 3, len(raw) - (4 * MIB - 5)
    _assert_cut_mid_line(raw, head_end, tail_start)

    full = parse_gcode_payload("part.gcode", raw)
    excerpt = parse_gcode_excerpt("part.gcode", len(raw), raw[:head_end], raw[tail_start:])

    assert full["infill_filament_weight_g"] is not None
    assert full["support_filament_weight_g"] is not None
    assert full["print_time_seconds"] == 8 * 3600 + 43 * 60 + 10
    for field in _SUMMARY_FIELDS:
        assert excerpt[field] == full[field], field
    assert excerpt["file_size_bytes"] == len(raw)
    assert [{key: item[key] for key in _MATERIAL_FIELDS} for item in excerpt["materials"]] == [
        {key: item[key] for key in _MATERIAL_FIELDS} for item in full["materials"]
    ]
    assert excerpt["materials"][0]["vendor"] == "Generic"

    assert excerpt["detail_level"] == "summary"
    assert "detail_level" not in full
    for field in _PER_TOOLPATH_FIELDS:
        assert excerpt[field] is None, field
    assert excerpt["support_roles_detected"] == []
    assert all(
        group["extrusion_share"] is None and group["material_weights_g"] == {}
        for group in excerpt["object_groups"]
    )
    assert all("infill_weight_g" not in item for item in excerpt["materials"])


def test_a_line_cut_in_half_is_dropped_but_a_file_cut_without_a_gap_is_whole() -> None:
    raw = (
        b"; generated by OrcaSlicer 2.3.0\n"
        b"; estimated printing time (normal mode) = 1h\n"
        b"; total filament used [g] = 25.5\n"
        + b"G1 X1 Y1 E1\n" * 3
        + b"; layer_height = 0.2\n"
    )
    cut = raw.index(b"= 25.5") + len(b"= 2")

    contiguous = parse_gcode_excerpt("a.gcode", len(raw), raw[:cut], raw[cut:])
    with_gap = parse_gcode_excerpt("a.gcode", len(raw) + 50, raw[:cut], raw[cut + 10 :])

    assert contiguous["total_filament_weight_g"] == 25.5
    assert with_gap["total_filament_weight_g"] is None
    assert with_gap["print_time_seconds"] == 3600


