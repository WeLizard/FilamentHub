def test_slice_info_filament_id_beyond_the_tool_limit_is_ignored() -> None:
    slice_info = _SLICE_INFO.replace(
        '<filament id="2" tray_info_idx="GFG99"',
        '<filament id="1000000000" tray_info_idx="GFG99"',
    )

    started = time.perf_counter()
    first, second = parse_gcode_3mf_excerpt(
        "a.gcode.3mf", 1000, {"metadata/slice_info.config": slice_info.encode()}
    )

    assert time.perf_counter() - started < 2
    assert [item["tool_index"] for item in first["materials"]] == [0]
    assert all(item["tool_index"] <= 255 for item in second["materials"])
    assert second["total_filament_weight_g"] == 3.2


def _form(container: str, file_name: str, size: int = 123456) -> dict[str, str]:
    return {"file_name": file_name, "file_size_bytes": str(size), "container": container}


def _entry(path: str, payload: bytes) -> tuple[str, tuple[str, bytes, str]]:
    return ("entry", (path, payload, "application/octet-stream"))


